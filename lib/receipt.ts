import { PDFDocument, StandardFonts, rgb } from "pdf-lib";

export type ReceiptData = { reference: string; label: string; status: string; amount: number; currency: "NGN" | "USD"; credit: boolean; at: Date; rows: [string, string][]; customer: string };
// The built-in PDF font can't print every symbol (like the naira sign), so we write amounts as "NGN 10,000.00" and replace odd characters.
const safe = (s: string) => s.replace(/[^\x20-\x7E]/g, "?").slice(0, 80);
export const plainMoney = (minor: number, c: string) => `${c} ${(minor / 100).toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

/** A one-page A5 PDF receipt. */
export async function buildReceipt(d: ReceiptData): Promise<Uint8Array> {
  const pdf = await PDFDocument.create(); pdf.setTitle(`Givar receipt ${d.reference}`); pdf.setProducer("Givar");
  const page = pdf.addPage([420, 595]); const regular = await pdf.embedFont(StandardFonts.Helvetica), bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const ink = rgb(0.06, 0.07, 0.04), mut = rgb(0.38, 0.4, 0.33), lime = rgb(0.85, 0.95, 0.29);
  page.drawRectangle({ x: 0, y: 515, width: 420, height: 80, color: lime });
  page.drawSvgPath("M 16 2 L 30 16 L 16 30 L 2 16 Z M 16 9 L 23 16 L 16 23 L 9 16 Z", { x: 28, y: 570, scale: 1.1, borderColor: ink, borderWidth: 1.6 });
  page.drawText("Givar", { x: 70, y: 548, size: 22, font: bold, color: ink });
  page.drawText("Transaction receipt", { x: 70, y: 530, size: 11, font: regular, color: ink });
  page.drawText(`${d.credit ? "+" : "-"}${plainMoney(d.amount, d.currency)}`, { x: 28, y: 465, size: 28, font: bold, color: ink });
  page.drawText(safe(`${d.label} - ${d.status}`), { x: 28, y: 442, size: 12, font: regular, color: mut });
  let y = 405;
  const rows: [string, string][] = [["Reference", d.reference], ["Date", d.at.toUTCString().replace(" GMT", " UTC")], ["Account", d.customer], ...d.rows];
  for (const [k, v] of rows) {
    page.drawLine({ start: { x: 28, y: y + 14 }, end: { x: 392, y: y + 14 }, thickness: 0.5, color: rgb(0.85, 0.86, 0.82) });
    page.drawText(safe(k), { x: 28, y, size: 10, font: regular, color: mut });
    const val = safe(v), w = regular.widthOfTextAtSize(val, 10);
    page.drawText(val, { x: Math.max(150, 392 - w), y, size: 10, font: bold, color: ink }); y -= 26;
  }
  page.drawText("This receipt was generated by Givar.app. Keep it for your records.", { x: 28, y: 40, size: 8, font: regular, color: mut });
  page.drawText("Questions? support@givar.app", { x: 28, y: 28, size: 8, font: regular, color: mut });
  return pdf.save();
}
